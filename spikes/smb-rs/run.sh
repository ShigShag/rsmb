#!/usr/bin/env bash
# Stage 0 spike for the `smb` crate (smb-rs). Prints one results table.
#   spikes/smb-rs/run.sh          all steps (about 20 minutes with the environment to itself)
#   spikes/smb-rs/run.sh 3 7      only these steps (1 2 3 4 5 6 7 7c 8 9 10 10i 11 12 13)
# Two builds:
#   pin      smb + smb-rpc from upstream git f4524d0 (= release 0.12.1 + the #183 listing-hang fix)
#   patched  the same plus patches/*.patch (guest login, pipe read, interim credits)
# Every step runs on "patched"; steps 1, 2 and 5 also on "pin", to show what fails without the patches.
# Steps that disturb the shared environment or time a 1 GiB transfer take the exclusive lock on
# /tmp/rsmb-env.lock, the others a shared one. Step 10 always undoes blackhole and pause.
# Do not edit this file while it runs (bash reads it as it goes).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
export REPO=$(cd "$here/../.." && pwd)
lock=/tmp/rsmb-env.lock
rev=f4524d032c8951cc288e1c8231ad68588583abda
steps=("$@")
[ ${#steps[@]} -gt 0 ] || steps=(1 2 3 4 5 6 7 7c 8 9 10 10i 11 12 13)

# build "pin"
cargo build --release -q --manifest-path "$here/Cargo.toml"
pin=$here/target/release/spike-smbrs

# build "patched": upstream checkout at the pin, patches applied, cargo [patch] via --config
src=$here/target/smb-rs-src
[ -d "$src/.git" ] || git clone -q https://github.com/afiffon/smb-rs "$src"
git -C "$src" checkout -q -f "$rev"
for p in "$here"/patches/*.patch; do git -C "$src" apply "$p"; done
cfg=()
for c in smb smb-rpc smb-msg smb-msg-derive smb-dtyp smb-dtyp-derive smb-fscc smb-transport; do
    cfg+=(--config "patch.'https://github.com/afiffon/smb-rs'.$c.path='$src/crates/$c'")
done
cp "$here/Cargo.lock" "$here/target/Cargo.lock.keep"   # the patched build must not rewrite the lock file
CARGO_TARGET_DIR=$here/target/patched cargo build --release -q --manifest-path "$here/Cargo.toml" \
    --features patched "${cfg[@]}"
mv "$here/target/Cargo.lock.keep" "$here/Cargo.lock"
patched=$here/target/patched/release/spike-smbrs
patch_lines=$(cat "$here"/patches/*.patch | grep -c '^[+-][^+-]' || true)

out=$(mktemp)
table() {
    echo
    echo "smb-rs spike: pin = git ${rev:0:7}; patched = pin + patches/ ($patch_lines changed lines)."
    echo "$(date -u +%Y-%m-%dT%H:%MZ), Samba $(docker exec rsmb-samba smbd -V 2>/dev/null)"
    drops_after=$("$REPO"/testenv/ctl.sh drops) || drops_after=unknown
    echo "netem drops on wan: $drops_before before, $drops_after after the run"
    [ "$drops_before" = "$drops_after" ] && [ "$drops_after" != unknown ] \
        || echo "WARNING: netem dropped packets on wan (or could not be asked); slow-endpoint times are suspect"
    echo "| step | item | endpoint | result | detail |"
    echo "|---|---|---|---|---|"
    grep '^ROW' "$out" | cut -f2- | sed 's/|/\\|/g; s/\t/ | /g; s/^/| /; s/$/ |/'
    rm -f "$out"
}
# An interrupted step 10 must not leave samba paused or the blackhole on.
undo() { "$REPO"/testenv/ctl.sh unpause samba 2>/dev/null || true; "$REPO"/testenv/ctl.sh blackhole off 2>/dev/null || true; }
drops_before=$("$REPO"/testenv/ctl.sh drops) || drops_before=unknown
if [[ " ${steps[*]} " == *" 10 "* ]]; then
    trap 'undo; table' EXIT   # the table is printed even if something below fails
else
    trap table EXIT
fi
trap 'exit 130' INT TERM

cost() {
    local t0 dir lockfile_crates smb_crates secs
    lockfile_crates=$(grep -c '^name = ' "$here/Cargo.lock")
    smb_crates=$(cargo tree -q --manifest-path "$here/Cargo.toml" -p smb -e normal --prefix none \
        | sed 's/ (\*)//; s/ (proc-macro)//' | sort -u | wc -l)
    printf 'ROW\t12\tcrates in Cargo.lock (spike: smb, smb-rpc, sspi, tokio, tokio-socks, futures, sha2, smbtap)\t-\tINFO\t%s\n' "$lockfile_crates"
    printf 'ROW\t12\tcrates in the dependency tree of smb alone (normal edges, incl. smb)\t-\tINFO\t%s\n' "$smb_crates"
    dir=$(mktemp -d)
    t0=$SECONDS
    CARGO_TARGET_DIR=$dir cargo build --release -q --manifest-path "$here/Cargo.toml"
    secs=$((SECONDS - t0))
    rm -rf "$dir"
    printf 'ROW\t12\tclean release build of the spike (fresh target dir, sources already downloaded, %s cores)\t-\tINFO\t%ss\n' "$(nproc)" "$secs"
    printf 'ROW\t12\tgit pin\t-\tINFO\tsmb + smb-rpc at upstream main %s = 0.12.1 + #183 (QueryDirectoryStream hang, 8+/4- lines), unreleased\n' "${rev:0:7}"
    for p in "$here"/patches/*.patch; do
        printf 'ROW\t12\tpatch %s\t-\tINFO\t%s changed lines\n' "$(basename "$p")" "$(grep -c '^[+-][^+-]' "$p")"
    done
    printf 'ROW\t12\tworkaround code outside the crate\t-\tINFO\town NDR32 srvsvc NetrShareEnum (shares_ndr32 + helpers in src/main.rs, about 145 lines incl. comments): the crate speaks NDR64 only, Samba refuses it\n'
    printf 'ROW\t12\tNT-hash login\t-\tINFO\tsspi 0.21.3: password "$NTLM$:<32 hex>" is taken as the NT hash (ntlm/messages/computations.rs); not tried\n'
    printf 'ROW\t12\tKerberos\t-\tINFO\tsmb cargo feature "kerberos" (adds reqwest), AuthMethodsConfig.kerberos; not tried\n'
}

# run <tag> <bin> <step>: rows get the build tag in front of the item
run() {
    local tag=$1 bin=$2 s=$3 mode=-s
    case $s in 5|6|7c|8|10|11) mode=-x ;; esac
    echo "== step $s ($tag)" >&2
    if [ "$s" = 10 ]; then
        flock -x "$lock" bash -c 'timeout 1800 "$1" 10; rc=$?; "$2"/testenv/ctl.sh blackhole off; "$2"/testenv/ctl.sh unpause samba 2>/dev/null; exit $rc' _ "$bin" "$REPO"
    else
        flock "$mode" "$lock" timeout 1800 "$bin" "$s"
    fi | awk -F'\t' -v OFS='\t' -v t="$tag" '$1 == "ROW" { $3 = "[" t "] " $3 } { print }' >>"$out" \
        || echo "step $s ($tag) exited non-zero" >&2
}

for s in "${steps[@]}"; do
    if [ "$s" = 12 ]; then cost >>"$out"; continue; fi
    case $s in 1|2|5) run pin "$pin" "$s" ;; esac
    run patched "$patched" "$s"
done

